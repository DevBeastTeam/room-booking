<?php
/**
 * ==============================================================================
 * Monar Pass Apartments - Live Chat API (server backed, works across devices)
 * ==============================================================================
 * The visitor widget used to store every conversation in localStorage, which
 * meant the leasing team could only see chats that happened in the SAME
 * browser. This API persists conversations server side so every visitor chat
 * shows up in the admin "Live Chat" inbox.
 *
 * Storage:
 *   1. MySQL (chat_sessions / chat_messages) — primary.
 *   2. JSON file (backend/data/chat.json)    — fallback when MySQL is down.
 *
 * Actions
 *   PUBLIC  POST start                      -> create / refresh a chat session
 *   PUBLIC  POST message                   -> visitor sends a message
 *   PUBLIC  GET  poll                      -> visitor polls for admin replies
 *   ADMIN   GET  sessions                  -> list all sessions (permission livechat)
 *   ADMIN   GET  sessions_count            -> cheap unread/total counters
 *   ADMIN   GET  messages                  -> messages of one session (marks read)
 *   ADMIN   POST reply                     -> admin replies (csrf)
 *   ADMIN   POST close                     -> close a session (csrf)
 *   ADMIN   POST delete                    -> delete a session + its messages (csrf)
 *
 * The session_key is a server generated bearer token (32 hex chars). It is the
 * only thing a visitor needs to read/write their own conversation.
 * ==============================================================================
 */

if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'OPTIONS') {
    http_response_code(200);
    exit();
}

require_once dirname(__DIR__) . '/config/database.php';
require_once __DIR__ . '/_auth.php';

auth_send_cors_headers();

$method    = strtoupper($_SERVER['REQUEST_METHOD'] ?? 'GET');
$rawInput  = file_get_contents('php://input');
$jsonInput = json_decode($rawInput, true);
if (!is_array($jsonInput)) $jsonInput = [];
$action = trim((string)($_GET['action'] ?? ($jsonInput['action'] ?? ($_POST['action'] ?? ''))));

// ── Limits & helpers ──────────────────────────────────────────────────────────
const CHAT_MAX_MESSAGE_LEN = 2000;
const CHAT_MAX_NAME_LEN    = 191;
const CHAT_MAX_EMAIL_LEN   = 191;
const CHAT_MAX_UNIT_LEN    = 32;
const CHAT_MAX_SESSIONS    = 500;

/** Current timestamp in MySQL DATETIME format. */
function chat_now() {
    return date('Y-m-d H:i:s');
}

/** Convert a DATETIME string (or a numeric stamp) into a JS millisecond epoch. */
function chat_ms($ts) {
    if (empty($ts)) return 0;
    if (is_numeric($ts)) return (int) $ts;
    $t = strtotime((string) $ts);
    return $t ? $t * 1000 : 0;
}

/** Sanitise a free text field (strip tags + clamp length). */
function chat_clean_text($value, $maxLen) {
    $text = strip_tags((string) $value);
    $text = trim($text);
    if ($text === '') return '';
    if (function_exists('mb_substr')) {
        if (mb_strlen($text, 'UTF-8') > $maxLen) {
            $text = mb_substr($text, 0, $maxLen, 'UTF-8');
        }
    } else {
        if (strlen($text) > $maxLen) $text = substr($text, 0, $maxLen);
    }
    return $text;
}

/** A session key is a hex token generated by the server. */
function chat_valid_key($key) {
    $key = trim((string) $key);
    if ($key === '') return false;
    return (bool) preg_match('/^[a-f0-9]{16,128}$/i', $key);
}

function chat_new_key() {
    return bin2hex(random_bytes(16));
}

// ── Storage layer: MySQL with a JSON file fallback ────────────────────────────

/** PDO handle or null (the connection is attempted only once per request). */
function chat_pdo() {
    static $tried = false;
    static $pdo   = null;
    if ($tried) return $pdo;
    $tried = true;
    $pdo = getDatabaseConnection();
    return $pdo ?: null;
}

function chat_json_path() {
    return dirname(__DIR__) . '/data/chat.json';
}

function chat_json_read() {
    $path = chat_json_path();
    if (!file_exists($path)) return ['sessions' => [], 'messages' => []];
    $raw = @file_get_contents($path);
    $arr = json_decode((string) $raw, true);
    if (!is_array($arr)) $arr = [];
    return [
        'sessions' => isset($arr['sessions']) && is_array($arr['sessions']) ? array_values($arr['sessions']) : [],
        'messages' => isset($arr['messages']) && is_array($arr['messages']) ? array_values($arr['messages']) : [],
    ];
}

function chat_json_write(array $data) {
    $path = chat_json_path();
    $dir  = dirname($path);
    if (!is_dir($dir)) @mkdir($dir, 0755, true);
    $payload = json_encode([
        'sessions' => array_values($data['sessions'] ?? []),
        'messages' => array_values($data['messages'] ?? []),
    ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    @file_put_contents($path, $payload, LOCK_EX);
}

/**
 * Read -> mutate -> write the JSON store under an exclusive lock.
 * The callback receives the store by reference and may modify it.
 */
function chat_json_mutate(callable $fn) {
    $path = chat_json_path();
    $dir  = dirname($path);
    if (!is_dir($dir)) @mkdir($dir, 0755, true);

    $handle = @fopen($path, 'c+');
    if ($handle === false) {
        // Extremely unlikely — fall back to a plain read/write cycle.
        $data = chat_json_read();
        $fn($data);
        chat_json_write($data);
        return $data;
    }

    @flock($handle, LOCK_EX);
    $raw   = stream_get_contents($handle);
    $arr   = json_decode((string) $raw, true);
    if (!is_array($arr)) $arr = [];
    $data = [
        'sessions' => isset($arr['sessions']) && is_array($arr['sessions']) ? array_values($arr['sessions']) : [],
        'messages' => isset($arr['messages']) && is_array($arr['messages']) ? array_values($arr['messages']) : [],
    ];

    $fn($data);

    $payload = json_encode([
        'sessions' => array_values($data['sessions'] ?? []),
        'messages' => array_values($data['messages'] ?? []),
    ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    ftruncate($handle, 0);
    rewind($handle);
    fwrite($handle, $payload);
    fflush($handle);
    @flock($handle, LOCK_UN);
    fclose($handle);

    return $data;
}

/** Find a session row inside the JSON store. */
function chat_json_find_session(array $sessions, $key) {
    foreach ($sessions as $row) {
        if (($row['session_key'] ?? '') === $key) return $row;
    }
    return null;
}

/** Find messages of a session inside the JSON store. */
function chat_json_messages_of(array $messages, $key, $limit = 200) {
    $out = [];
    foreach ($messages as $m) {
        if (($m['session_key'] ?? '') === $key) $out[] = $m;
    }
    usort($out, function ($a, $b) {
        $ta = strtotime((string)($a['created_at'] ?? '1970-01-01 00:00:00'));
        $tb = strtotime((string)($b['created_at'] ?? '1970-01-01 00:00:00'));
        if ($ta === $tb) return (int)($a['id'] ?? 0) <=> (int)($b['id'] ?? 0);
        return $ta <=> $tb;
    });
    if ($limit > 0 && count($out) > $limit) {
        $out = array_slice($out, -$limit);
    }
    return $out;
}

function chat_json_next_id(array $messages) {
    $max = 0;
    foreach ($messages as $m) {
        $id = (int)($m['id'] ?? 0);
        if ($id > $max) $max = $id;
    }
    return $max + 1;
}

// ── Store API (DB first, JSON fallback) ───────────────────────────────────────

/** Fetch one session row (or null). */
function chat_store_session($key) {
    if (!chat_valid_key($key)) return null;
    $pdo = chat_pdo();
    if ($pdo) {
        try {
            $stmt = $pdo->prepare('SELECT * FROM chat_sessions WHERE session_key = ? LIMIT 1');
            $stmt->execute([$key]);
            $row = $stmt->fetch();
            return $row ?: null;
        } catch (PDOException $e) {
            error_log('[chat] session lookup failed: ' . $e->getMessage());
            return null;
        }
    }
    $data = chat_json_read();
    return chat_json_find_session($data['sessions'], $key);
}

/** All session rows, newest activity first. */
function chat_store_sessions() {
    $pdo = chat_pdo();
    if ($pdo) {
        try {
            $stmt = $pdo->query('SELECT * FROM chat_sessions ORDER BY last_ts DESC, id DESC');
            return $stmt->fetchAll();
        } catch (PDOException $e) {
            error_log('[chat] session list failed: ' . $e->getMessage());
            return [];
        }
    }
    $data   = chat_json_read();
    $rows   = $data['sessions'];
    usort($rows, function ($a, $b) {
        $ta = strtotime((string)($a['last_ts'] ?? '1970-01-01 00:00:00'));
        $tb = strtotime((string)($b['last_ts'] ?? '1970-01-01 00:00:00'));
        if ($ta === $tb) return (int)($b['id'] ?? 0) <=> (int)($a['id'] ?? 0);
        return $tb <=> $ta;
    });
    return $rows;
}

/** Create a session row. */
function chat_store_create_session(array $row) {
    $now  = $row['created_at'] ?? chat_now();
    $pdo  = chat_pdo();
    if ($pdo) {
        try {
            $stmt = $pdo->prepare(
                'INSERT INTO chat_sessions (session_key, visitor_name, visitor_email, visitor_unit, status, unread_admin, last_message, last_ts, created_at)
                 VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)'
            );
            $stmt->execute([
                $row['session_key'],
                $row['visitor_name'] ?? 'Guest',
                $row['visitor_email'] ?? null,
                $row['visitor_unit'] ?? null,
                $row['status'] ?? 'open',
                (int)($row['unread_admin'] ?? 0),
                $row['last_message'] ?? null,
                $row['last_ts'] ?? $now,
                $now,
            ]);
            return true;
        } catch (PDOException $e) {
            error_log('[chat] session create failed: ' . $e->getMessage());
            return false;
        }
    }
    chat_json_mutate(function (&$data) use ($row) {
        $row['id']        = chat_json_next_id($data['messages']) + 100000;
        $row['created_at'] = $row['created_at'] ?? chat_now();
        array_unshift($data['sessions'], $row);
        if (count($data['sessions']) > CHAT_MAX_SESSIONS) {
            $data['sessions'] = array_slice($data['sessions'], 0, CHAT_MAX_SESSIONS);
        }
    });
    return true;
}

/** Update mutable columns of a session. */
function chat_store_update_session($key, array $fields) {
    if (!chat_valid_key($key)) return false;
    $allowed = ['visitor_name', 'visitor_email', 'visitor_unit', 'status', 'unread_admin', 'last_message', 'last_ts'];
    $fields  = array_intersect_key($fields, array_flip($allowed));
    if (empty($fields)) return false;

    $pdo = chat_pdo();
    if ($pdo) {
        try {
            $sets = [];
            $vals = [];
            foreach ($fields as $col => $val) {
                $sets[] = "`$col` = ?";
                $vals[] = $val;
            }
            $vals[] = $key;
            $stmt = $pdo->prepare('UPDATE chat_sessions SET ' . implode(', ', $sets) . ' WHERE session_key = ?');
            $stmt->execute($vals);
            return true;
        } catch (PDOException $e) {
            error_log('[chat] session update failed: ' . $e->getMessage());
            return false;
        }
    }

    chat_json_mutate(function (&$data) use ($key, $fields) {
        foreach ($data['sessions'] as $i => $row) {
            if (($row['session_key'] ?? '') === $key) {
                $data['sessions'][$i] = array_merge($row, $fields);
                return;
            }
        }
    });
    return true;
}

/** Delete a session and all of its messages. */
function chat_store_delete_session($key) {
    if (!chat_valid_key($key)) return false;
    $pdo = chat_pdo();
    if ($pdo) {
        try {
            $stmt = $pdo->prepare('DELETE FROM chat_messages WHERE session_key = ?');
            $stmt->execute([$key]);
            $stmt = $pdo->prepare('DELETE FROM chat_sessions WHERE session_key = ?');
            $stmt->execute([$key]);
            return true;
        } catch (PDOException $e) {
            error_log('[chat] session delete failed: ' . $e->getMessage());
            return false;
        }
    }
    chat_json_mutate(function (&$data) use ($key) {
        $data['sessions'] = array_values(array_filter($data['sessions'], function ($row) use ($key) {
            return ($row['session_key'] ?? '') !== $key;
        }));
        $data['messages'] = array_values(array_filter($data['messages'], function ($row) use ($key) {
            return ($row['session_key'] ?? '') !== $key;
        }));
    });
    return true;
}

/** Insert a message row. Returns the stored row. */
function chat_store_add_message(array $row) {
    $now = chat_now();
    $pdo = chat_pdo();
    if ($pdo) {
        try {
            $stmt = $pdo->prepare(
                'INSERT INTO chat_messages (session_key, sender, message, read_by_admin, created_at) VALUES (?, ?, ?, ?, ?)'
            );
            $stmt->execute([
                $row['session_key'],
                $row['sender'] ?? 'user',
                $row['message'] ?? '',
                (int)($row['read_by_admin'] ?? 0),
                $now,
            ]);
            $id = (int) $pdo->lastInsertId();
            return [
                'id'           => $id,
                'session_key'  => $row['session_key'],
                'sender'       => $row['sender'] ?? 'user',
                'message'      => $row['message'] ?? '',
                'read_by_admin'=> (int)($row['read_by_admin'] ?? 0),
                'created_at'   => $now,
            ];
        } catch (PDOException $e) {
            error_log('[chat] message insert failed: ' . $e->getMessage());
            return null;
        }
    }

    $stored = null;
    chat_json_mutate(function (&$data) use ($row, $now, &$stored) {
        $stored = [
            'id'            => chat_json_next_id($data['messages']),
            'session_key'   => $row['session_key'],
            'sender'        => $row['sender'] ?? 'user',
            'message'       => $row['message'] ?? '',
            'read_by_admin' => (int)($row['read_by_admin'] ?? 0),
            'created_at'    => $now,
        ];
        $data['messages'][] = $stored;
        if (count($data['messages']) > 5000) {
            $data['messages'] = array_slice($data['messages'], -5000);
        }
    });
    return $stored;
}

/** Messages of one session (oldest first). */
function chat_store_messages($key, $limit = 200) {
    if (!chat_valid_key($key)) return [];
    $pdo = chat_pdo();
    if ($pdo) {
        try {
            $sql = 'SELECT * FROM chat_messages WHERE session_key = ? ORDER BY id ASC';
            $stmt = $pdo->prepare($sql);
            $stmt->execute([$key]);
            $rows = $stmt->fetchAll();
            if ($limit > 0 && count($rows) > $limit) $rows = array_slice($rows, -$limit);
            return $rows;
        } catch (PDOException $e) {
            error_log('[chat] message list failed: ' . $e->getMessage());
            return [];
        }
    }
    $data = chat_json_read();
    return chat_json_messages_of($data['messages'], $key, $limit);
}

/** Mark every message of a session as read by the admin. */
function chat_store_mark_read($key) {
    if (!chat_valid_key($key)) return false;
    $pdo = chat_pdo();
    if ($pdo) {
        try {
            $stmt = $pdo->prepare('UPDATE chat_messages SET read_by_admin = 1 WHERE session_key = ?');
            $stmt->execute([$key]);
            return true;
        } catch (PDOException $e) {
            error_log('[chat] mark read failed: ' . $e->getMessage());
            return false;
        }
    }
    chat_json_mutate(function (&$data) use ($key) {
        foreach ($data['messages'] as $i => $m) {
            if (($m['session_key'] ?? '') === $key) $data['messages'][$i]['read_by_admin'] = 1;
        }
    });
    return true;
}

// ── Public shaping helpers ────────────────────────────────────────────────────

function chat_session_public(array $row, $messages = null) {
    $key = (string)($row['session_key'] ?? '');
    $out = [
        'session_key'  => $key,
        'userId'       => $key,
        'displayName'  => ((string)($row['visitor_name'] ?? '')) !== '' ? (string)$row['visitor_name'] : 'Guest',
        'email'        => (string)($row['visitor_email'] ?? ''),
        'unit'         => (string)($row['visitor_unit'] ?? ''),
        'status'       => ((string)($row['status'] ?? 'open')) !== '' ? (string)$row['status'] : 'open',
        'unread'       => (int)($row['unread_admin'] ?? 0),
        'last_message' => (string)($row['last_message'] ?? ''),
        'lastTs'       => chat_ms($row['last_ts'] ?? null),
        'createdAt'    => chat_ms($row['created_at'] ?? null),
    ];
    if ($messages !== null) {
        $out['messages'] = array_map('chat_message_public', $messages);
    }
    return $out;
}

function chat_message_public(array $row) {
    return [
        'id'           => (int)($row['id'] ?? 0),
        'session_key'  => (string)($row['session_key'] ?? ''),
        'sender'       => ((string)($row['sender'] ?? 'user')) === 'admin' ? 'admin' : 'user',
        'text'         => (string)($row['message'] ?? ''),
        'ts'           => chat_ms($row['created_at'] ?? null),
        'created_at'   => (string)($row['created_at'] ?? ''),
    ];
}

// ─────────────────────────────────────────────────────────────────────────────
// Dispatch
// ─────────────────────────────────────────────────────────────────────────────

switch ($action) {

    // ── PUBLIC: create / refresh a chat session ───────────────────────────────
    case 'start': {
        if ($method !== 'POST') {
            auth_json_out(false, ['error' => 'Use POST for action=start.'], 405);
        }
        $name  = chat_clean_text($jsonInput['name'] ?? ($_POST['name'] ?? ''), CHAT_MAX_NAME_LEN);
        $email = chat_clean_text($jsonInput['email'] ?? ($_POST['email'] ?? ''), CHAT_MAX_EMAIL_LEN);
        $unit  = chat_clean_text($jsonInput['unit'] ?? ($_POST['unit'] ?? ''), CHAT_MAX_UNIT_LEN);
        if ($email !== '' && !filter_var($email, FILTER_VALIDATE_EMAIL)) {
            $email = '';
        }
        if ($name === '') $name = 'Guest';

        $existingKey = trim((string)($jsonInput['session_key'] ?? ($_POST['session_key'] ?? '')));
        $session     = ($existingKey !== '' && chat_valid_key($existingKey)) ? chat_store_session($existingKey) : null;

        if ($session) {
            // Refresh the visitor details on an existing session.
            $updates = [];
            if ($name !== '' && $name !== (string)($session['visitor_name'] ?? '')) {
                $updates['visitor_name'] = $name;
            }
            if ($email !== '' && $email !== (string)($session['visitor_email'] ?? '')) {
                $updates['visitor_email'] = $email;
            }
            if ($unit !== '' && $unit !== (string)($session['visitor_unit'] ?? '')) {
                $updates['visitor_unit'] = $unit;
            }
            if (!empty($updates)) chat_store_update_session($session['session_key'], $updates);
            $session = chat_store_session($session['session_key']);
        } else {
            $key = chat_new_key();
            $ok  = chat_store_create_session([
                'session_key'   => $key,
                'visitor_name'  => $name,
                'visitor_email' => $email !== '' ? $email : null,
                'visitor_unit'  => $unit !== '' ? $unit : null,
                'status'        => 'open',
                'unread_admin'  => 0,
                'last_message'  => null,
                'last_ts'       => chat_now(),
                'created_at'    => chat_now(),
            ]);
            if (!$ok) {
                auth_json_out(false, ['error' => 'Could not start the chat session.'], 500);
            }
            $session = chat_store_session($key);

            // Welcome message from the leasing team.
            $greetingName = ($name !== '' && $name !== 'Guest') ? $name : 'there';
            chat_store_add_message([
                'session_key'   => $key,
                'sender'        => 'admin',
                'message'       => "Hi $greetingName! 👋 Welcome to Monar Pass. How can our leasing team assist you today? "
                                 . 'Feel free to ask about floor plans, pricing, tour schedules, or specials!',
                'read_by_admin' => 1,
            ]);
            chat_store_update_session($key, [
                'last_message' => 'Welcome to Monar Pass — how can we help?',
                'last_ts'     => chat_now(),
            ]);
            $session = chat_store_session($key);
        }

        $messages = chat_store_messages($session['session_key'], 200);
        auth_json_out(true, [
            'session_key'  => $session['session_key'],
            'visitor_name' => (string)($session['visitor_name'] ?? 'Guest'),
            'visitor_email'=> (string)($session['visitor_email'] ?? ''),
            'visitor_unit' => (string)($session['visitor_unit'] ?? ''),
            'session'      => chat_session_public($session, $messages),
            'messages'     => array_map('chat_message_public', $messages),
        ]);
    }

    // ── PUBLIC: visitor sends a message ───────────────────────────────────────
    case 'message': {
        if ($method !== 'POST') {
            auth_json_out(false, ['error' => 'Use POST for action=message.'], 405);
        }
        $key = trim((string)($jsonInput['session_key'] ?? ($_POST['session_key'] ?? '')));
        if (!chat_valid_key($key)) {
            auth_json_out(false, ['error' => 'Invalid or missing session key.'], 400);
        }
        $session = chat_store_session($key);
        if (!$session) {
            auth_json_out(false, ['error' => 'Chat session not found.'], 404);
        }

        $text = chat_clean_text($jsonInput['message'] ?? ($_POST['message'] ?? ''), CHAT_MAX_MESSAGE_LEN);
        if ($text === '') {
            auth_json_out(false, ['error' => 'Message cannot be empty.'], 400);
        }

        $stored = chat_store_add_message([
            'session_key'   => $key,
            'sender'        => 'user',
            'message'       => $text,
            'read_by_admin' => 0,
        ]);
        if (!$stored) {
            auth_json_out(false, ['error' => 'Could not store the message.'], 500);
        }

        chat_store_update_session($key, [
            'unread_admin' => (int)($session['unread_admin'] ?? 0) + 1,
            'last_message' => $text,
            'last_ts'      => chat_now(),
        ]);

        auth_json_out(true, ['message' => chat_message_public($stored)]);
    }

    // ── PUBLIC: visitor polls for admin replies ───────────────────────────────
    case 'poll': {
        $key = trim((string)($_GET['session_key'] ?? ($jsonInput['session_key'] ?? '')));
        if (!chat_valid_key($key)) {
            auth_json_out(false, ['error' => 'Invalid or missing session key.'], 400);
        }
        $session = chat_store_session($key);
        if (!$session) {
            auth_json_out(false, ['error' => 'Chat session not found.'], 404);
        }
        $messages = chat_store_messages($key, 200);
        auth_json_out(true, [
            'session'  => chat_session_public($session, $messages),
            'messages' => array_map('chat_message_public', $messages),
        ]);
    }

    // ── ADMIN: list every session ─────────────────────────────────────────────
    case 'sessions': {
        auth_require_permission('livechat');
        $onlyKey = trim((string)($_GET['session_key'] ?? ''));
        $rows    = chat_store_sessions();
        $out     = [];
        foreach ($rows as $row) {
            $key = (string)($row['session_key'] ?? '');
            if ($onlyKey !== '' && $key !== $onlyKey) continue;
            if ($onlyKey !== '') {
                $messages = chat_store_messages($key, 50);
                $out[] = chat_session_public($row, $messages);
            } else {
                $out[] = chat_session_public($row);
            }
        }
        $unread = 0;
        foreach ($out as $s) $unread += (int)$s['unread'];
        auth_json_out(true, [
            'sessions' => $out,
            'total'    => count($out),
            'unread'   => $unread,
        ]);
    }

    // ── ADMIN: cheap counters for the sidebar badge ───────────────────────────
    case 'sessions_count': {
        auth_require_permission('livechat');
        $rows   = chat_store_sessions();
        $unread = 0;
        foreach ($rows as $row) $unread += (int)($row['unread_admin'] ?? 0);
        auth_json_out(true, [
            'total'   => count($rows),
            'unread'  => $unread,
            'open'    => count(array_filter($rows, function ($r) { return ($r['status'] ?? 'open') === 'open'; })),
            'closed'  => count(array_filter($rows, function ($r) { return ($r['status'] ?? '') === 'closed'; })),
        ]);
    }

    // ── ADMIN: messages of one session (also marks it as read) ─────────────────
    case 'messages': {
        auth_require_permission('livechat');
        $key = trim((string)($_GET['session_key'] ?? ($jsonInput['session_key'] ?? '')));
        if (!chat_valid_key($key)) {
            auth_json_out(false, ['error' => 'Invalid or missing session key.'], 400);
        }
        $session = chat_store_session($key);
        if (!$session) {
            auth_json_out(false, ['error' => 'Chat session not found.'], 404);
        }
        $messages = chat_store_messages($key, 200);
        chat_store_mark_read($key);
        chat_store_update_session($key, ['unread_admin' => 0]);
        $session = chat_store_session($key);
        auth_json_out(true, [
            'session'  => chat_session_public($session, $messages),
            'messages' => array_map('chat_message_public', $messages),
        ]);
    }

    // ── ADMIN: reply ───────────────────────────────────────────────────────────
    case 'reply': {
        auth_require_permission('livechat');
        auth_require_csrf_if_mutating();
        if ($method !== 'POST') {
            auth_json_out(false, ['error' => 'Use POST for action=reply.'], 405);
        }
        $key = trim((string)($jsonInput['session_key'] ?? ($_POST['session_key'] ?? '')));
        if (!chat_valid_key($key)) {
            auth_json_out(false, ['error' => 'Invalid or missing session key.'], 400);
        }
        $session = chat_store_session($key);
        if (!$session) {
            auth_json_out(false, ['error' => 'Chat session not found.'], 404);
        }
        $text = chat_clean_text($jsonInput['message'] ?? ($_POST['message'] ?? ''), CHAT_MAX_MESSAGE_LEN);
        if ($text === '') {
            auth_json_out(false, ['error' => 'Reply cannot be empty.'], 400);
        }
        $stored = chat_store_add_message([
            'session_key'   => $key,
            'sender'        => 'admin',
            'message'       => $text,
            'read_by_admin' => 1,
        ]);
        if (!$stored) {
            auth_json_out(false, ['error' => 'Could not store the reply.'], 500);
        }
        chat_store_update_session($key, [
            'last_message' => $text,
            'last_ts'      => chat_now(),
            'status'       => 'open',
        ]);
        auth_log('chat_reply', 'Session ' . $key);
        auth_json_out(true, ['message' => chat_message_public($stored)]);
    }

    // ── ADMIN: close a session ────────────────────────────────────────────────
    case 'close': {
        auth_require_permission('livechat');
        auth_require_csrf_if_mutating();
        if ($method !== 'POST') {
            auth_json_out(false, ['error' => 'Use POST for action=close.'], 405);
        }
        $key = trim((string)($jsonInput['session_key'] ?? ($_POST['session_key'] ?? '')));
        if (!chat_valid_key($key)) {
            auth_json_out(false, ['error' => 'Invalid or missing session key.'], 400);
        }
        if (!chat_store_session($key)) {
            auth_json_out(false, ['error' => 'Chat session not found.'], 404);
        }
        // Default: close. Pass status=open to reopen the conversation.
        $status = (string)($jsonInput['status'] ?? 'closed');
        $status = ($status === 'open') ? 'open' : 'closed';
        chat_store_update_session($key, ['status' => $status]);
        auth_log('chat_close', 'Session ' . $key . ' → ' . $status);
        auth_json_out(true, ['session_key' => $key, 'status' => $status]);
    }

    // ── ADMIN: delete a session ───────────────────────────────────────────────
    case 'delete': {
        auth_require_permission('livechat');
        auth_require_csrf_if_mutating();
        if ($method !== 'POST') {
            auth_json_out(false, ['error' => 'Use POST for action=delete.'], 405);
        }
        $key = trim((string)($jsonInput['session_key'] ?? ($_POST['session_key'] ?? '')));
        if (!chat_valid_key($key)) {
            auth_json_out(false, ['error' => 'Invalid or missing session key.'], 400);
        }
        chat_store_delete_session($key);
        auth_log('chat_delete', 'Session ' . $key);
        auth_json_out(true, ['session_key' => $key, 'deleted' => true]);
    }

    default:
        auth_json_out(false, [
            'error'   => 'Unknown action.',
            'actions' => [
                'start', 'message', 'poll',
                'sessions', 'sessions_count', 'messages',
                'reply', 'close', 'delete',
            ],
        ], 400);
}
